/**
 * 根據小時數回傳時間問候詞。
 * 05–11 → 早安　12–17 → 午安　18–21 → 晚安　22–04 → 夜深了
 */
export function getTimeGreeting(hour?: number): string {
  const h = hour ?? new Date().getHours();
  if (h >= 5  && h < 12) return '早安';
  if (h >= 12 && h < 18) return '午安';
  if (h >= 18 && h < 22) return '晚安';
  return '夜深了';
}

/**
 * 根據日期（天數 mod 100）回傳當日問候語。
 * 同一天呼叫多次結果相同；隔天自動換下一條。
 */
export function getDailyMessage(date: Date = new Date()): string {
  const daysSinceEpoch = Math.floor(date.getTime() / 86_400_000);
  return MESSAGES[daysSinceEpoch % 100];
}

/** 依索引取得問候語（0–99）。供測試瀏覽用。 */
export function getMessageByIndex(index: number): string {
  return MESSAGES[((index % 100) + 100) % 100];
}

/** 回傳今日對應的索引（0–99）。供測試起始點用。 */
export function getTodayIndex(date: Date = new Date()): number {
  return Math.floor(date.getTime() / 86_400_000) % 100;
}
